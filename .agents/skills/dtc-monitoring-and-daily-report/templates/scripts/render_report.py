def render(data: dict[str, Any], config: dict[str, Any]) -> str:
    """Render the daily report Markdown.

    `data` keys:
        store_name, store_domain, currency, date_label, generated_at,
        sources (list[str]), shopify (dict), clarity (dict), judgeme (dict|None),
        clarity_status, judgeme_status (status strings for degradation),
        growth (optional sanitized trigger/action summary)
    """
    lang = (config.get("language") or "en").lower()
    if lang not in STRINGS:
        lang = "en"
    L = STRINGS[lang]
    currency = data.get("currency") or "USD"

    store_name = data.get("store_name") or data.get("store_domain", "Store")
    date_label = data["date_label"]
    sources = data.get("sources", [])
    shopify = data.get("shopify") or {}
    clarity = data.get("clarity") or {}
    judgeme = data.get("judgeme")

    rev = shopify.get("revenue", 0.0)
    orders_count = shopify.get("count", 0)
    paid_count = shopify.get("paid_count", 0)
    aov = shopify.get("aov", 0.0)
    products_count = shopify.get("active_products", 0)
    all_time_orders = shopify.get("all_time_orders", 0)

    sessions = clarity.get("human_sessions", 0)
    bot_sessions = clarity.get("bot_sessions", 0)
    cvr = (orders_count / sessions * 100) if sessions > 0 else 0
    cvr_badge = _badge(cvr, 1.5, 0.5) if sessions else "⚪"

    # ------- Header -------
    md = f"# {L['title'].format(store=store_name, date=date_label)}\n\n"
    md += f"> {L['generated_at']}: {data.get('generated_at', '')}  \n"
    md += f"> {L['data_date']}: **{date_label}**  \n"
    md += f"> {L['data_sources']}: {' + '.join(sources) if sources else '—'}\n\n---\n\n"

    # ------- KPIs -------
    md += L["kpi_section"] + "\n\n"
    md += f"| {L['kpi_metric']} | {L['kpi_value']} | {L['kpi_health']} |\n|---|---|---|\n"
    md += f"| {L['revenue']} | **{_money(rev, currency)}** | {'🟢' if rev > 0 else '⚪'} |\n"
    md += f"| {L['orders']} | **{orders_count}** | {'🟢' if orders_count > 0 else '⚪'} |\n"
    md += f"| {L['paid_orders']} | {paid_count} | — |\n"
    md += f"| {L['aov']} | {_money(aov, currency)} | {_badge(aov, 45, 25) if aov else '⚪'} |\n"
    md += f"| {L['sessions']} | **{sessions}** | {'🟢' if sessions >= 20 else ('🟡' if sessions >= 5 else '🔴')} |\n"
    md += f"| {L['bot_sessions']} | {bot_sessions} | — |\n"
    md += f"| {L['cvr']} | **{cvr:.2f}%** | {cvr_badge} |\n"
    md += f"| {L['active_products']} | {products_count} | {'🟢' if products_count >= 15 else ('🟡' if products_count >= 5 else '🔴')} |\n"
    md += f"| {L['all_time_orders']} | {all_time_orders} | — |\n\n---\n\n"

    # ------- Traffic profile -------
    md += L["traffic_section"] + "\n\n"
    if data.get("clarity_status") == "ok":
        md += f"| {L['dim']} | Top 1 |\n|---|---|\n"
        md += f"| {L['country']} | {clarity.get('top_country', '—')} |\n"
        md += f"| {L['device']} | {clarity.get('top_device', '—')} |\n"
        md += f"| {L['browser']} | {clarity.get('top_browser', '—')} |\n"
        md += f"| {L['scroll_depth']} | {clarity.get('avg_scroll_depth', 0)}% |\n"
        md += f"| {L['engagement']} | {_fmt_seconds(clarity.get('engagement_time_sec', 0))} |\n\n"

        md += L["popular_pages"] + "\n\n"
        if clarity.get("popular_pages"):
            md += f"| # | {L['page']} | {L['views']} |\n|---|---|---|\n"
            domain = data.get("store_domain", "")
            for i, p in enumerate(clarity["popular_pages"][:5], 1):
                url = (p.get("url") or "").replace(f"https://{domain}", "") or "/"
                md += f"| {i} | `{url}` | {p.get('visits', 0)} |\n"
        else:
            md += L["no_data"] + "\n"

        md += "\n" + L["referrers_section"] + "\n\n"
        if clarity.get("referrers"):
            md += f"| {L['referrer']} | Sessions |\n|---|---|\n"
            for r in clarity["referrers"][:5]:
                md += f"| {r.get('name', 'Direct')} | {r.get('sessions', 0)} |\n"
        else:
            md += L["no_data"] + "\n"
    else:
        reason = data.get("clarity_reason") or data.get("clarity_status", "unknown")
        md += L["section_unavailable"].format(reason=reason) + "\n"
    md += "\n---\n\n"

    # ------- UX health -------
    md += L["ux_section"] + "\n\n" + L["ux_intro"] + "\n\n"
    if data.get("clarity_status") == "ok":
        rage = clarity.get("rage_clicks", 0)
        dead = clarity.get("dead_clicks", 0)
        quick = clarity.get("quick_backs", 0)
        jse = clarity.get("js_errors", 0)
        excs = clarity.get("excessive_scroll", 0)

        md += f"| {L['ux_check']} | {L['ux_count']} | {L['ux_status']} |\n|---|---|---|\n"
        md += f"| {L['rage_clicks']} | {rage} | {_zero_badge(rage)} |\n"
        md += f"| {L['dead_clicks']} | {dead} | {'🟢' if dead == 0 else '🟡'} |\n"
        md += f"| {L['quick_backs']} | {quick} | {'🟢' if quick == 0 else '🟡'} |\n"
        md += f"| {L['js_errors']} | {jse} | {'🟢' if jse == 0 else '🔴'} |\n"
        md += f"| {L['excessive_scroll']} | {excs} | {'🟢' if excs == 0 else '🟡'} |\n"
    else:
        reason = data.get("clarity_reason") or data.get("clarity_status", "unknown")
        md += L["section_unavailable"].format(reason=reason) + "\n"
    md += "\n---\n\n"

    # ------- Reviews (only when judgeme returned ok) -------
    if data.get("judgeme_status") == "ok" and judgeme:
        md += L["reviews_section"] + "\n\n"
        md += f"| {L['kpi_metric']} | {L['kpi_value']} |\n|---|---|\n"
        md += f"| {L['review_total']} | **{judgeme.get('total_count', 0)}** |\n"
        md += f"| {L['avg_rating']} | {judgeme.get('average_rating', 0) or '—'} ⭐ |\n\n"
        rd = judgeme.get("rating_distribution") or {}
        if rd:
            md += L["rating_dist"] + ":\n\n"
            for star in [5, 4, 3, 2, 1]:
                n = rd.get(star, 0)
                bar = "█" * n if n > 0 else ""
                md += f"- {star}⭐ {bar} {n}\n"
            md += "\n"
        md += "---\n\n"

    # ------- Deterministic growth triggers and action ledger -------
    if data.get("growth"):
        md += _render_growth(data["growth"], lang)

    # ------- Insights -------
    insights, actions = _build_insights_and_actions(L, lang, sessions, rev, clarity, products_count)
    md += L["insights_section"] + "\n\n"
    for i in insights:
        md += f"- {i}\n"
    md += "\n---\n\n" + L["actions_section"] + "\n\n"
    for i, a in enumerate(actions[:5], 1):
        md += f"{i}. {a}\n"

    # ------- Quick links -------
    md += "\n---\n\n" + L["links_section"] + "\n\n"
    md += f"| {L['tool']} | {L['link']} |\n|---|---|\n"
    domain = data.get("store_domain", "")
    if domain:
        store_handle = domain.replace(".myshopify.com", "")
        md += f"| {L['storefront']} | https://{domain} |\n"
        md += f"| {L['shopify_admin']} | https://admin.shopify.com/store/{store_handle} |\n"
    clarity_pid = config.get("clarity", {}).get("project_id")
    if clarity_pid:
        md += f"| {L['clarity_link']} | https://clarity.microsoft.com/projects/view/{clarity_pid}/dashboard |\n"

    md += "\n" + L["footer"] + "\n"
    return md


def _build_insights_and_actions(
    L: dict[str, str],
    lang: str,
    sessions: int,
    rev: float,
    clarity: dict[str, Any],
    products_count: int,
) -> tuple[list[str], list[str]]:
    insights: list[str] = []
    actions: list[str] = []

    if rev == 0 and sessions == 0:
        insights.append(L["insight_zero_traffic"])
    elif rev == 0 and sessions > 0:
        insights.append(L["insight_traffic_no_orders"].format(sessions=sessions))

    if clarity.get("rage_clicks", 0) > 0:
        insights.append(L["insight_rage"].format(n=clarity["rage_clicks"]))
        actions.append(
            "Fix Rage Click source (Clarity Recordings -> filter `rage_click`)"
        )
    if clarity.get("js_errors", 0) > 0:
        insights.append(L["insight_js"].format(n=clarity["js_errors"]))
        actions.append("Fix JS errors")
    sd = clarity.get("avg_scroll_depth", 0)
    if sd >= 80:
        insights.append(L["insight_scroll_high"].format(pct=sd))
    elif 0 < sd < 50:
        insights.append(L["insight_scroll_low"].format(pct=sd))

    if not insights:
        insights.append(L["insight_default"])
    if not actions:
        if products_count < 10:
            actions.append(L["action_more_products"].format(n=products_count))
        actions.append(L["action_review_recordings"])
        actions.append(L["action_content"])

    return insights, actions
