def _inline(value: Any) -> str:
    return str(value if value is not None else "—").replace("\n", " ").replace("\r", " ").replace("|", "\\|")


def _render_growth(growth: dict[str, Any], lang: str) -> str:
    copy = _GROWTH_COPY.get(lang, _GROWTH_COPY["en"])
    triggers = growth.get("triggers") or {}
    md = copy["heading"] + "\n\n"
    md += f"| {copy['capability']} | {copy['decision']} | {copy['reason']} | {copy['records']} |\n|---|---|---|---|\n"
    for name in ("new_product", "campaign_recommendation"):
        item = triggers.get(name) or {}
        matched = item.get("matched")
        decision = copy["yes"] if matched is True else copy["no"] if matched is False else copy["unknown"]
        reason = item.get("reason_code") or "NOT_EVALUATED"
        count = len(item.get("source_ids") or [])
        md += f"| {copy[name]} | {decision} | `{reason}` | {count} |\n"
    campaigns = growth.get("campaign_recommendations") or []
    if campaigns:
        campaign_heading, draft_notice = _CAMPAIGN_COPY.get(lang, _CAMPAIGN_COPY["en"])
        md += f"\n{campaign_heading}\n\n"
        for campaign in campaigns:
            product = campaign.get("product") or {}
            plan = campaign.get("recommended_plan") or {}
            title = _inline(product.get("title"))
            recommendation_id = _inline(campaign.get("recommendation_id"))
            decision = _inline(campaign.get("decision"))
            readiness = _inline(campaign.get("publish_readiness"))
            summary = ""
            if plan:
                summary = (
                    f" · {plan.get('horizon_days', '—')}d"
                    f"/{plan.get('recommended_post_count', '—')} posts"
                    f"/{_inline(plan.get('recommended_channel'))}"
                )
            md += f"- **{title}** · `{recommendation_id}` · `{decision}` · `{readiness}`{summary}\n"
            reasons = campaign.get("reason_codes") or []
            blockers = campaign.get("blocker_codes") or []
            options = campaign.get("user_options") or []
            if reasons:
                md += f"  - reasons: {', '.join(f'`{_inline(item)}`' for item in reasons)}\n"
            if blockers:
                md += f"  - blockers: {', '.join(f'`{_inline(item)}`' for item in blockers)}\n"
            if options:
                md += f"  - options: {', '.join(f'`{_inline(item)}`' for item in options)}\n"
            if campaign.get("decision") == "recommended":
                md += f"  - {draft_notice}\n"
    actions = growth.get("actions") or []
    if actions:
        md += f"\n**{copy['actions']}**\n\n"
        for action in actions:
            md += f"- `{action.get('action_key', '—')}` · {action.get('action_type', '—')} · **{action.get('status', '—')}**\n"
    return md + "\n---\n\n"


