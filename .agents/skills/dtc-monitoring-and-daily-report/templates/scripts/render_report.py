CURRENCY_SYMBOLS = {
    "USD": "$", "EUR": "€", "GBP": "£", "JPY": "¥", "CNY": "¥", "AUD": "A$",
    "CAD": "C$", "HKD": "HK$", "SGD": "S$", "INR": "₹", "KRW": "₩", "BRL": "R$",
}


def _money(amount: float, currency_code: str) -> str:
    sym = CURRENCY_SYMBOLS.get(currency_code, f"{currency_code} ")
    return f"{sym}{amount:,.2f}"


def _fmt_seconds(s: int) -> str:
    if s < 60:
        return f"{s}s"
    return f"{s // 60}m {s % 60}s"


def _badge(value: float, good: float, ok: float) -> str:
    if value >= good:
        return "🟢"
    if value >= ok:
        return "🟡"
    return "🔴"


def _zero_badge(n: int) -> str:
    return "🟢" if n == 0 else ("🟡" if n < 3 else "🔴")


